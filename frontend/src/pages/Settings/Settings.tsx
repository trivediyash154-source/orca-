import { useUI, type ConstellationSize } from '../../state/UIContext';

const CONSTELLATION_SIZES: ReadonlyArray<{ value: ConstellationSize; label: string }> = [
  { value: 0, label: 'Off (planning entities only)' },
  { value: 2000, label: '2,000 objects' },
  { value: 5000, label: '5,000 objects (default)' },
  { value: 10000, label: '10,000 objects' },
];

/** Brief §49/Phase 12 §21: only settings that actually do something. Every control below is
 * read by a named consumer (`UIContext.tsx` documents which one per field) and visibly
 * changes the scene — there are no decorative toggles. Presentation Mode has its own entry
 * point in the top bar, so it is not duplicated here. */
export function SettingsPage() {
  const ui = useUI();

  const toggles: ReadonlyArray<{ label: string; hint: string; value: boolean; set: (on: boolean) => void }> = [
    {
      label: 'Earth rotation',
      hint: 'Adds a presentational idle drift on top of the real sidereal angle derived from simulation time.',
      value: ui.earthRotation,
      set: ui.setEarthRotation,
    },
    {
      label: 'Clouds',
      hint: 'Renders the separate cloud shell, which drifts slightly faster than the surface.',
      value: ui.showClouds,
      set: ui.setShowClouds,
    },
    {
      label: 'Atmosphere',
      hint: 'Renders the two additive atmospheric limb shells around Earth.',
      value: ui.showAtmosphere,
      set: ui.setShowAtmosphere,
    },
    {
      label: 'Starfield',
      hint: 'Deep-space background.',
      value: ui.showStarfield,
      set: ui.setShowStarfield,
    },
    {
      label: 'Constellation orbit ribbons',
      hint: 'Batched orbital-shell ribbons for the synthetic constellation (one draw call for all of them).',
      value: ui.showConstellationRibbons,
      set: ui.setShowConstellationRibbons,
    },
    {
      label: 'Planning-entity orbit rings',
      hint: "Per-orbit rings for the engine's own real satellites and rescue vehicles.",
      value: ui.showOrbitRings,
      set: ui.setShowOrbitRings,
    },
    {
      label: 'Mission trajectories',
      hint: 'Transfer legs of every dispatched mission.',
      value: ui.showTrajectories,
      set: ui.setShowTrajectories,
    },
    {
      label: 'Proximity visualization',
      hint: 'Colour objects by real distance from the selection instead of by orbital band.',
      value: ui.proximityMode,
      set: ui.setProximityMode,
    },
    {
      label: 'Reduce motion',
      hint: 'Disables the animated emergency pulse ring.',
      value: ui.reducedMotion,
      set: ui.setReducedMotion,
    },
    {
      label: 'Performance mode',
      hint: 'Halves the rendered constellation instance count and drops ribbons — for weaker GPUs.',
      value: ui.performanceMode,
      set: ui.setPerformanceMode,
    },
  ];

  return (
    <div className="settings-page">
      <section className="settings-section">
        <h2>Visual Constellation</h2>
        <label className="settings-field">
          <span>Object count</span>
          <select
            value={ui.constellationSize}
            onChange={(e) => ui.setConstellationSize(Number(e.target.value) as ConstellationSize)}
          >
            {CONSTELLATION_SIZES.map((s) => (
              <option key={s.value} value={s.value}>
                {s.label}
              </option>
            ))}
          </select>
        </label>
        <p className="muted settings-hint">
          Synthetic visualization objects generated by <code>orca_engine --visualScenario</code>{' '}
          (<code>visualShell</code> family). They are real orbital mechanics but are NOT real-world
          satellites and never enter the mission-planning graph.
        </p>

        <label className="settings-field">
          <span>Altitude exaggeration ({ui.altitudeExaggeration.toFixed(0)}×)</span>
          <input
            type="range"
            min={1}
            max={20}
            step={1}
            value={ui.altitudeExaggeration}
            onChange={(e) => ui.setAltitudeExaggeration(Number(e.target.value))}
          />
        </label>
        <p className="muted settings-hint">
          A documented VISUALIZATION transform only (<code>coordinates.ts</code>). At true scale a
          500 km and an 800 km orbit differ by 4% of Earth's radius and collapse into one line on
          screen. 1× is near-true scale. This never alters any computed or reported value — every
          distance the UI reports is in real kilometres.
        </p>
      </section>

      <section className="settings-section">
        <h2>Scene</h2>
        {toggles.map((t) => (
          <label key={t.label} className="settings-toggle settings-toggle-block">
            <input type="checkbox" checked={t.value} onChange={(e) => t.set(e.target.checked)} />
            <span>
              {t.label}
              <span className="settings-toggle-hint">{t.hint}</span>
            </span>
          </label>
        ))}
      </section>
    </div>
  );
}
