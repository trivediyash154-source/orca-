import { useEffect, useMemo, useRef, useState } from 'react';
import type { ThreeEvent } from '@react-three/fiber';
import {
  AdditiveBlending,
  BufferAttribute,
  Color,
  type InstancedMesh,
  Object3D,
  type Points,
} from 'three';

import { eciToSceneExaggerated, SCENE_SCALE_KM } from '../coordinates';
import { getMarkerGlowTexture } from '../satellites/markerGlowTexture';
import { OrbitalRibbons, SelectedOrbitRibbon } from './OrbitalRibbons';
import type { VisualObjectView } from '../../types/engine';

const dummy = new Object3D();
const tmpColor = new Color();

const NEAR_COLOR = new Color('#4fd6ff');
const MEDIUM_COLOR = new Color('#ffb84d');
const FAR_COLOR = new Color('#ff5a5a');
const SELECTED_COLOR = new Color('#ffffff');

/** Band colours -- the same LEO/MEO/GEO palette `OrbitalRibbons` and `tokens.css` use, so a
 * satellite and its shell's ribbon read as the same family. */
const BAND_COLOR: Record<string, Color> = {
  LEO: new Color('#5fc8ff'),
  MEO: new Color('#a878ff'),
  GEO: new Color('#ff7ab8'),
};
const DEFAULT_BAND = new Color('#8fd0ff');

export interface ConstellationLayerProps {
  readonly satellites: readonly VisualObjectView[];
  readonly vehicles: readonly VisualObjectView[];
  readonly selectedId: string | null;
  readonly onSelect: (id: string) => void;
  readonly proximityMode: boolean;
  readonly exaggeration: number;
  readonly showRibbons: boolean;
  readonly performanceMode: boolean;
}

/** The synthetic VISUAL constellation (Phase 12 brief §1/§6/§7) -- thousands of objects,
 * rendered as exactly TWO GPU primitives per kind:
 *
 *   1. one `THREE.InstancedMesh` (shared low-poly geometry + one shared material) carrying
 *      every solid body, positioned via `setMatrixAt` into a typed matrix buffer;
 *   2. one `THREE.Points` glow layer sharing a single sprite texture.
 *
 * Never one component/mesh/DOM node per satellite (brief §1's explicit prohibition).
 *
 * **These objects are SYNTHETIC visualization data** -- deterministically generated by
 * `orca_engine --visualScenario` from real orbital mechanics, but they are NOT real-world
 * satellites and are NOT part of the mission-planning graph. The UI labels them as such
 * (`Scene.tsx`'s overlay); the real planning entities render separately via
 * `EntityMarkerField`. */
export function ConstellationLayer({
  satellites,
  vehicles,
  selectedId,
  onSelect,
  proximityMode,
  exaggeration,
  showRibbons,
  performanceMode,
}: ConstellationLayerProps) {
  const meshRef = useRef<InstancedMesh>(null);
  const pointsRef = useRef<Points>(null);
  const vehicleMeshRef = useRef<InstancedMesh>(null);
  const [hoveredIndex, setHoveredIndex] = useState<number | null>(null);
  const glowTexture = useMemo(() => getMarkerGlowTexture(), []);

  // Performance mode subsamples the instance count rather than changing how anything is
  // drawn -- a real, measurable lever, not a quality placebo.
  const sats = useMemo(
    () => (performanceMode && satellites.length > 2500 ? satellites.filter((_, i) => i % 2 === 0) : satellites),
    [satellites, performanceMode],
  );

  const positions = useMemo(
    () => sats.map((s) => eciToSceneExaggerated(s.position, exaggeration)),
    [sats, exaggeration],
  );
  const vehiclePositions = useMemo(
    () => vehicles.map((v) => eciToSceneExaggerated(v.position, exaggeration)),
    [vehicles, exaggeration],
  );

  const selectedIndex = useMemo(
    () => (selectedId !== null ? sats.findIndex((s) => s.id === selectedId) : -1),
    [sats, selectedId],
  );

  /** Real Euclidean distances (in true km, from the raw engine-reported positions -- NOT the
   * exaggerated display coordinates) from the selected object. Brief §8/§22: the proximity
   * encoding must be a real measurement, so it deliberately bypasses the visual transform. */
  const proximity = useMemo(() => {
    if (!proximityMode || selectedIndex < 0) return null;
    const origin = sats[selectedIndex]!.position;
    const distances = sats.map((s) =>
      Math.hypot(s.position.x - origin.x, s.position.y - origin.y, s.position.z - origin.z),
    );
    let max = 0;
    for (let i = 0; i < distances.length; i++) {
      if (i !== selectedIndex && distances[i]! > max) max = distances[i]!;
    }
    return { distances, max: Math.max(max, 1e-6) };
  }, [proximityMode, selectedIndex, sats]);

  const glowBuffers = useMemo(
    () => ({
      pos: new Float32Array(Math.max(sats.length, 1) * 3),
      col: new Float32Array(Math.max(sats.length, 1) * 3),
    }),
    [sats.length],
  );

  // One pass writes BOTH the instance matrices/colors and the glow buffers -- iterating the
  // constellation twice at 10K objects would be pure waste.
  useEffect(() => {
    const mesh = meshRef.current;
    const geometry = pointsRef.current?.geometry;
    for (let i = 0; i < sats.length; i++) {
      const s = sats[i]!;
      const [x, y, z] = positions[i]!;

      if (i === selectedIndex) tmpColor.copy(SELECTED_COLOR);
      else if (proximity) {
        const ratio = proximity.distances[i]! / proximity.max;
        tmpColor.copy(ratio < 0.33 ? NEAR_COLOR : ratio < 0.66 ? MEDIUM_COLOR : FAR_COLOR);
      } else {
        tmpColor.copy(BAND_COLOR[s.band ?? ''] ?? DEFAULT_BAND);
        if (i === hoveredIndex) tmpColor.lerp(SELECTED_COLOR, 0.5);
      }

      if (mesh) {
        dummy.position.set(x, y, z);
        dummy.scale.setScalar(i === selectedIndex ? 3.2 : i === hoveredIndex ? 2.2 : 1);
        dummy.updateMatrix();
        mesh.setMatrixAt(i, dummy.matrix);
        mesh.setColorAt(i, tmpColor);
      }

      glowBuffers.pos[i * 3] = x;
      glowBuffers.pos[i * 3 + 1] = y;
      glowBuffers.pos[i * 3 + 2] = z;
      glowBuffers.col[i * 3] = tmpColor.r;
      glowBuffers.col[i * 3 + 1] = tmpColor.g;
      glowBuffers.col[i * 3 + 2] = tmpColor.b;
    }
    if (mesh) {
      mesh.count = sats.length;
      mesh.instanceMatrix.needsUpdate = true;
      if (mesh.instanceColor) mesh.instanceColor.needsUpdate = true;
      mesh.computeBoundingSphere();
    }
    if (geometry) {
      (geometry.getAttribute('position') as BufferAttribute).needsUpdate = true;
      (geometry.getAttribute('color') as BufferAttribute).needsUpdate = true;
      geometry.computeBoundingSphere();
    }
  }, [sats, positions, selectedIndex, hoveredIndex, proximity, glowBuffers]);

  // Rescue vehicles: their own instanced mesh with a visibly different (octahedral, larger)
  // silhouette -- brief §7's "rescue vehicles must have a visibly different model/marker".
  useEffect(() => {
    const mesh = vehicleMeshRef.current;
    if (!mesh) return;
    tmpColor.set('#5bffb0');
    for (let i = 0; i < vehicles.length; i++) {
      const [x, y, z] = vehiclePositions[i]!;
      dummy.position.set(x, y, z);
      dummy.scale.setScalar(vehicles[i]!.id === selectedId ? 2.4 : 1);
      dummy.updateMatrix();
      mesh.setMatrixAt(i, dummy.matrix);
      mesh.setColorAt(i, tmpColor);
    }
    mesh.count = vehicles.length;
    mesh.instanceMatrix.needsUpdate = true;
    if (mesh.instanceColor) mesh.instanceColor.needsUpdate = true;
    mesh.computeBoundingSphere();
  }, [vehicles, vehiclePositions, selectedId]);

  const handleClick = (e: ThreeEvent<MouseEvent>) => {
    e.stopPropagation();
    if (e.instanceId === undefined) return;
    const s = sats[e.instanceId];
    if (s) onSelect(s.id);
  };

  const handleVehicleClick = (e: ThreeEvent<MouseEvent>) => {
    e.stopPropagation();
    if (e.instanceId === undefined) return;
    const v = vehicles[e.instanceId];
    if (v) onSelect(v.id);
  };

  if (sats.length === 0) return null;

  return (
    <>
      {showRibbons && !performanceMode && (
        <OrbitalRibbons objects={sats} exaggeration={exaggeration} />
      )}

      {/* The selected object's own orbit, always drawn (even with the batched field off) so
          a selection is never invisible. */}
      <SelectedOrbitRibbon
        object={selectedIndex >= 0 ? sats[selectedIndex]! : null}
        exaggeration={exaggeration}
      />

      {/* Glow halo -- one Points draw call for the entire constellation. */}
      <points ref={pointsRef} raycast={() => null}>
        <bufferGeometry>
          <bufferAttribute attach="attributes-position" args={[glowBuffers.pos, 3]} />
          <bufferAttribute attach="attributes-color" args={[glowBuffers.col, 3]} />
        </bufferGeometry>
        <pointsMaterial
          map={glowTexture}
          size={0.05}
          vertexColors
          transparent
          opacity={0.55}
          depthWrite={false}
          blending={AdditiveBlending}
          sizeAttenuation
        />
      </points>

      {/* Solid bodies -- one InstancedMesh, shared octahedron geometry + shared material. */}
      <instancedMesh
        ref={meshRef}
        args={[undefined, undefined, Math.max(sats.length, 1)]}
        onClick={handleClick}
        onPointerMove={(e) => {
          e.stopPropagation();
          setHoveredIndex(e.instanceId ?? null);
        }}
        onPointerOut={() => setHoveredIndex(null)}
      >
        <octahedronGeometry args={[0.0075, 0]} />
        <meshBasicMaterial toneMapped={false} />
      </instancedMesh>

      {vehicles.length > 0 && (
        <instancedMesh
          ref={vehicleMeshRef}
          args={[undefined, undefined, Math.max(vehicles.length, 1)]}
          onClick={handleVehicleClick}
        >
          <coneGeometry args={[0.016, 0.042, 5]} />
          <meshBasicMaterial toneMapped={false} />
        </instancedMesh>
      )}
    </>
  );
}

export { NEAR_COLOR, MEDIUM_COLOR, FAR_COLOR, SCENE_SCALE_KM };
