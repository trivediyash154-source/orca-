import { useState } from 'react';

import { ControlPanel } from '../../components/ControlPanel';
import { EmergencyQueue } from '../../components/mission/EmergencyQueue';
import { RescueOperations } from '../../components/mission/RescueOperations';
import { FleetReadiness } from '../../components/mission/FleetReadiness';
import { MissionIntelligence } from '../../components/mission/MissionIntelligence';
import { ObjectInspector } from '../../components/ObjectInspector';
import { ConstellationObjectPanel } from '../../components/ConstellationObjectPanel';
import { Scene, type CameraFocus } from '../../visualization/scene/Scene';
import { ProximityLegend } from '../../visualization/constellation/ProximityLegend';
import { useEngine } from '../../state/EngineContext';
import { useUI } from '../../state/UIContext';
import type { VisualObjectView } from '../../types/engine';

/** The flagship screen (brief §12, §68; Phase 12 §11): the orbital scene dominates. The
 * right column carries transport controls, mission intelligence, and per-object detail --
 * in that priority order (brief §70). Camera framing actions and the proximity toggle sit as
 * a thin overlay ON the scene rather than as more side-panel cards, so the 3D view stays the
 * hero (Phase 12 §11's "do not create giant empty black cards surrounding a tiny
 * visualization"). */
export function MissionControlPage() {
  const { proximityMode, setProximityMode, constellationSize } = useUI();
  const { dataSource } = useEngine();
  const [focusNonce, setFocusNonce] = useState(0);
  const [focusTarget, setFocusTarget] = useState<CameraFocus>('earth');
  const [syntheticObject, setSyntheticObject] = useState<VisualObjectView | null>(null);

  const focus = (target: CameraFocus) => {
    setFocusTarget(target);
    setFocusNonce((n) => n + 1);
  };

  return (
    <div className="mission-control-page">
      <div className="mission-control-scene">
        <Scene
          focusNonce={focusNonce}
          focusTarget={focusTarget}
          onConstellationSelect={setSyntheticObject}
          syntheticSelectedId={syntheticObject?.id ?? null}
        />

        <div className="scene-overlay scene-overlay-top">
          <button onClick={() => focus('earth')}>Reset View</button>
          <button onClick={() => focus('selected')}>Focus Selected</button>
          <button onClick={() => focus('mission')}>Focus Mission</button>
          <label className="scene-overlay-toggle">
            <input
              type="checkbox"
              checked={proximityMode}
              onChange={(e) => setProximityMode(e.target.checked)}
            />
            Proximity
          </label>
        </div>

        {constellationSize > 0 && (
          <div className="scene-overlay scene-overlay-bottom">
            <span className="scene-overlay-note">
              {constellationSize.toLocaleString()} synthetic visualization objects · generated by
              {dataSource === 'demo' ? (
                <> the in-browser constellation model</>
              ) : (
                <code> orca_engine --visualScenario</code>
              )}{' '}
              · not part of the planning graph
            </span>
          </div>
        )}

        {proximityMode && <ProximityLegend />}
      </div>

      {/* The rescue column. Ordered by the question an operator asks first: what needs rescue,
          what is being done about it, what could still respond, and only then the details of
          whatever is selected. The 3D scene answers "where"; this column answers "what and
          why", which is the part that makes ORCA a rescue system rather than a globe. */}
      <aside className="mission-control-side">
        <ControlPanel />
        {/* The operation itself leads. Everything below it -- the queue, the fleet, the
            inspector -- is supporting detail for the story this panel tells. */}
        <RescueOperations />
        <EmergencyQueue />
        <MissionIntelligence />
        <FleetReadiness />
        {syntheticObject ? (
          <ConstellationObjectPanel object={syntheticObject} onClose={() => setSyntheticObject(null)} />
        ) : (
          <ObjectInspector />
        )}
      </aside>
    </div>
  );
}
